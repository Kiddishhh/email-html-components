import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync,readFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {createCampaignEditorServer} from '../skills/build-omnisend-campaign-draft/editor/campaign-editor-server.mjs';
const workspaceRoot=resolve(import.meta.dirname,'..');
test('text styles persist per instance and template, reach upload source, and reset to identical default HTML',async t=>{
 const root=mkdtempSync(join(workspaceRoot,'build/text-style-test-'));
 const server=await createCampaignEditorServer({workspaceRoot,sessionRoot:root,templateRoot:join(root,'templates')});
 const base=await server.listen();t.after(async()=>{await server.close();rmSync(root,{recursive:true,force:true});});
 const call=async(path,body,method=body?'POST':'GET')=>{const r=await fetch(base+path,{method,headers:{'content-type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});assert.equal(r.ok,true,await r.clone().text());return r.json();};
 const {draft}=await call('/api/drafts',{name:'Type'});const path=`/api/drafts/${draft.id}`;
 let result=await call(path+'/components',{componentKey:'hero.minimalTitleCta'});const first=result.draft.components[0];
 result=await call(path+'/components',{componentKey:'hero.minimalTitleCta'});const second=result.draft.components[1];
 const preview=async()=>{const{previewUrl}=await call(path+'/preview',{});return(await fetch(base+previewUrl)).text();};
 const baseline=await preview();
 const styles={'hero.title':{fontFamily:'Georgia',fontSize:36,fontWeight:700,lineHeight:44,letterSpacing:1,color:'#123456',spaceBefore:12,spaceAfter:16,textAlign:'left'}};
 result=await call(path+`/components/${first.instanceId}`,{textStyles:styles},'PATCH');
 assert.deepEqual(result.draft.components[0].textStyles,styles);assert.equal(result.draft.components[1].textStyles,undefined);
 const updated=await preview();assert.match(updated,/font-size:36px;font-size:min\(36px,6vw\)/);assert.match(updated,/color:#123456/);
 assert.doesNotMatch(updated,/<script|<iframe|<form|data-freshine-editor-text/);
 const invalid=await fetch(base+path+`/components/${first.instanceId}`,{method:'PATCH',headers:{'content-type':'application/json'},body:JSON.stringify({textStyles:{'hero.title':{fontFamily:'Arial;position:fixed'}}})});assert.equal(invalid.status,400);
 assert.deepEqual((await call(path)).draft.components[0].textStyles,styles);
 const {template}=await call('/api/templates',{name:'Custom text',draftId:draft.id});const copy=(await call(`/api/templates/${template.id}/drafts`,{})).draft;
 assert.deepEqual(copy.components[0].textStyles,styles);assert.equal(copy.confirmed,false);
 for(const instance of [first,second])await call(path+`/components/${instance.instanceId}/confirm`,{});
 await call(path+'/prepare-omnisend-draft',{campaign:{name:'Type',subject:'Subject',preheader:'Preview'}});
 const composition=JSON.parse(readFileSync(join(root,draft.id,'composition.v1.json'),'utf8'));
 assert.deepEqual(composition.components[0].textStyles,styles);
 assert.match(readFileSync(composition.output,'utf8'),/font-size:36px;font-size:min\(36px,6vw\)/);
 result=await call(path+`/components/${first.instanceId}`,{textStyles:{'hero.title':{}}},'PATCH');assert.equal(result.draft.confirmed,false);
 assert.equal(await preview(),baseline);
});
