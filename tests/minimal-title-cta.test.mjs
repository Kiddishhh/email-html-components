import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { editableFieldKeys, editorFieldCopy } from '../skills/build-omnisend-campaign-draft/editor/public/editor-ui-contract.mjs';
import { addComponentInstance, buildEditorCatalog, createCampaignDocument } from '../skills/build-omnisend-campaign-draft/editor/campaign-editor-core.mjs';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const key = 'hero.minimalTitleCta';
const directory = resolve(root, '头图/极简标题CTA头图');
const imageUrl = 'https://freshinelife.com/cdn/shop/files/Arlise-100_-Blackout-Chenille-Drapes-OY12-278-5-2.webp?v=1769075754&width=1600';
const contentFields = ['hero.title', 'hero.subtitle', 'hero.cta.text', 'hero.cta.url', 'hero.image.url', 'hero.image.alt', 'hero.image.clickUrl'];

test('Minimal title CTA hero registers a complete independent component and editable fields', () => {
  const catalog = buildEditorCatalog({ workspaceRoot: root });
  const component = catalog.find(item => item.componentKey === key);
  assert.ok(component, 'hero.minimalTitleCta must be registered');
  const entry = JSON.parse(readFileSync(resolve(root, '组件清单.json'))).find(item => item.componentKey === key);
  assert.equal(entry.中文名称, '极简标题CTA头图');
  assert.equal(entry.分类, '头图');
  assert.equal(entry.输出宽度, 600);
  assert.equal(entry.移动端断点, 375);
  for (const file of Object.values(entry.路径)) assert.ok(existsSync(resolve(root, file)), file);
  assert.ok(existsSync(resolve(directory, '效果演示.html')));
  assert.deepEqual(editableFieldKeys(key), { content: contentFields, settings: ['color.surface', 'color.title', 'color.body', 'color.action'] });
  assert.equal(component.defaultSettings.values['color.surface'], '#F7ECDE');
  assert.equal(component.defaultSettings.values['color.title'], '#1F1F1F');
  assert.equal(component.defaultSettings.values['color.body'], '#5F5F5F');
  assert.equal(component.defaultSettings.values['color.action'], '#9C1C23');
  assert.equal(editorFieldCopy(key, 'content', 'hero.title').label, '主标题');
  assert.equal(editorFieldCopy(key, 'content', 'hero.image.clickUrl').label, '大图点击链接');
  const fixture = JSON.parse(readFileSync(resolve(directory, 'content.fixture.v1.json')));
  assert.equal(fixture.values['hero.image.url'], imageUrl);
  for (const text of ['hero.title', 'hero.subtitle', 'hero.cta.text']) assert.ok(fixture.values[text]);
});

test('Minimal title CTA hero renders the reference layout with editable copy, independent links and tracked image', () => {
  const catalog = buildEditorCatalog({ workspaceRoot: root });
  const document = addComponentInstance(createCampaignDocument({ name: 'minimal-title-cta-test' }), catalog, key);
  const temporary = mkdtempSync(resolve(tmpdir(), 'minimal-title-cta-'));
  const previewOutput = resolve(temporary, 'preview.html');
  const composition = { schemaVersion: 1, canvas: document.canvas, output: resolve(temporary, 'email.html'), previewOutput, components: document.components.map(({ name, directory, componentKey, content, settings }) => ({ name, directory, componentKey, content, settings })) };
  const input = resolve(temporary, 'composition.json');
  writeFileSync(input, JSON.stringify(composition));
  const result = spawnSync(process.execPath, ['build-email-template.v1.mjs', input], { cwd: root, encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr || result.stdout);
  const html = readFileSync(previewOutput, 'utf8');
  for (const text of ['IRIS', 'Rich linen texture with powerful light control, creating a cozy, peaceful retreat for restful days and quiet nights.', 'SHOP NOW']) assert.ok(html.includes(text), text);
  assert.ok(html.includes(imageUrl.replaceAll('&', '&amp;')), 'default image URL must survive attribute escaping');
  assert.match(html, /data-freshine-href-slot="hero\.cta\.url"/);
  assert.match(html, /data-freshine-href-slot="hero\.image\.clickUrl"/);
  assert.equal([...html.matchAll(/href="https:\/\/freshinelife\.com\/"/g)].length, 2, 'button and image links stay independent anchors');
  const titleStyle = html.match(/<td class="freshine-minimal-title"[^>]*style="([^"]*)"/)?.[1];
  assert.ok(titleStyle, 'title must retain its centered table cell');
  assert.match(titleStyle, /color:#1F1F1F;font-family:Lora,Georgia,'Times New Roman',serif;font-size:36px;font-size:min\(36px,6vw\);font-weight:400;line-height:54px;line-height:min\(54px,9vw\);letter-spacing:0px/);
  const subtitleStyle = html.match(/<td class="freshine-minimal-subtitle"[^>]*style="([^"]*)"/)?.[1];
  assert.ok(subtitleStyle, 'subtitle must retain its centered table cell');
  assert.match(subtitleStyle, /color:#5F5F5F;font-family:Montserrat,Arial,Helvetica,sans-serif;font-size:16px;font-size:min\(16px,2\.666667vw\);font-weight:500;line-height:24px;line-height:min\(24px,4vw\);letter-spacing:0px/);
  const ctaStyle = html.match(/<a[^>]*data-freshine-href-slot="hero\.cta\.url"[^>]*style="([^"]*)"/)?.[1];
  assert.ok(ctaStyle, 'tracked CTA must retain its editable anchor');
  assert.match(ctaStyle, /^display:block;padding:13px 30px;padding:min\(13px,2\.166667vw\) min\(30px,5vw\);/, 'button padding must live on the anchor so the whole button is clickable');
  assert.match(ctaStyle, /color:#FFFFFF;font-family:Montserrat,Arial,Helvetica,sans-serif;font-size:16px;font-size:min\(16px,2\.666667vw\);font-weight:600;line-height:20px;line-height:min\(20px,3\.333333vw\);letter-spacing:1px/);
  const ctaCell = html.match(/<td align="center" valign="middle" bgcolor="#9C1C23" style="([^"]*)"/)?.[1];
  assert.ok(ctaCell, 'CTA cell must keep its action color');
  assert.match(ctaCell, /border-radius:2px;border-radius:min\(2px,0\.333333vw\)/);
  assert.doesNotMatch(ctaCell, /padding:/, 'CTA cell must not duplicate the anchor padding');
  const imageStyle = html.match(/<img[^>]*data-freshine-slot="hero\.image"[^>]*style="([^"]*)"/)?.[1];
  assert.ok(imageStyle, 'image must remain an editable slot');
  assert.match(imageStyle, /display:block;width:100%;max-width:506px;height:auto/);
  const imageCell = html.match(/<td align="center" style="([^"]*)">\s*<a[^>]*data-freshine-href-slot="hero\.image\.clickUrl"/)?.[1];
  assert.ok(imageCell, 'image cell must share the 47px page margins without extra inset');
  assert.match(imageCell, /padding:28px 0 0 0;padding:min\(28px,4\.666667vw\) 0 0 0/);
  assert.doesNotMatch(html, /asset:\/\/|\{\{|FRESHINE_IF_SETTING|navigation\.visible/);
  const template = readFileSync(resolve(directory, 'component.template.v1.html'), 'utf8');
  assert.doesNotMatch(template, /<style\b|@media|display:\s*(?:flex|grid)|position:\s*(?:absolute|fixed)|<div\b/i);
  assert.match(template, /max-width:600px/);
  assert.match(template, /padding:min\(36px,6vw\) min\(47px,7\.833333vw\) min\(40px,6\.666667vw\) min\(47px,7\.833333vw\)/);
  const demo = readFileSync(resolve(directory, '效果演示.html'), 'utf8');
  for (const pattern of [/font-size:min\(36px,6vw\)/, /line-height:min\(54px,9vw\)/, /font-size:min\(16px,2\.666667vw\)/, /min\(28px,4\.666667vw\)/, /max-width:506px/]) assert.match(demo, pattern);
});
