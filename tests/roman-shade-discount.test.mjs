import test from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { editableFieldKeys, editorFieldCopy } from '../skills/build-omnisend-campaign-draft/editor/public/editor-ui-contract.mjs';
import { addComponentInstance, buildEditorCatalog, buildLocalAssetMap, createCampaignDocument } from '../skills/build-omnisend-campaign-draft/editor/campaign-editor-core.mjs';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const key = 'hero.romanShadeDiscount';
const directory = resolve(root, '头图/罗马帘专属折扣头图');
const cta = 'https://freshinelife.com/collections/roman-shades?utm_source=omnisend&utm_medium=email&utm_id=cover-fs';
const contentFields = ['hero.backgroundImage.url', 'hero.backgroundImage.alt', 'hero.logo.url', 'hero.logo.alt', 'hero.logo.clickUrl', 'hero.eyebrow', 'hero.title', 'hero.discount', 'hero.subtitle', 'hero.cta.text', 'hero.cta.url'];

test('Roman shade discount registers a complete independent component and editable fields', () => {
  const catalog = buildEditorCatalog({ workspaceRoot: root });
  const component = catalog.find(item => item.componentKey === key);
  assert.ok(component, 'hero.romanShadeDiscount must be registered');
  const entry = JSON.parse(readFileSync(resolve(root, '组件清单.json'))).find(item => item.componentKey === key);
  assert.equal(entry.中文名称, '罗马帘专属折扣头图');
  assert.equal(entry.输出宽度, 600);
  assert.equal(entry.移动端断点, 375);
  for (const file of Object.values(entry.路径)) assert.ok(existsSync(resolve(root, file)), file);
  assert.ok(existsSync(resolve(directory, '效果演示.html')));
  assert.deepEqual(editableFieldKeys(key), { content: contentFields, settings: ['navigation.visible', 'color.text', 'color.action'] });
  assert.equal(component.defaultSettings.values['navigation.visible'], true);
  assert.equal(component.defaultSettings.values['color.navigationLeft'], '#604211');
  assert.equal(component.defaultSettings.values['color.navigationRight'], '#6B492C');
  assert.equal(editorFieldCopy(key, 'content', 'hero.discount').label, '主折扣文案');
  const fixture = JSON.parse(readFileSync(resolve(directory, 'content.fixture.v1.json')));
  assert.equal(fixture.values['hero.cta.url'], cta);
  assert.equal(fixture.values['hero.logo.clickUrl'], 'https://freshinelife.com/');
  for (const file of Object.values(fixture.localReferenceAssets)) assert.ok(existsSync(resolve(directory, file)), file);
});

test('Roman shade discount renders the approved navigation while preserving copy and tracked CTA', () => {
  const catalog = buildEditorCatalog({ workspaceRoot: root });
  const document = addComponentInstance(createCampaignDocument({ name: 'roman-shade-test' }), catalog, key);
  const temporary = mkdtempSync(resolve(tmpdir(), 'roman-shade-discount-'));
  const previewOutput = resolve(temporary, 'preview.html');
  const composition = { schemaVersion: 1, canvas: document.canvas, output: resolve(temporary, 'email.html'), previewOutput, assets: buildLocalAssetMap(document, { workspaceRoot: root }), components: document.components.map(({ name, directory, componentKey, content, settings }) => ({ name, directory, componentKey, content, settings })) };
  const input = resolve(temporary, 'composition.json');
  writeFileSync(input, JSON.stringify(composition));
  const result = spawnSync(process.execPath, ['build-email-template.v1.mjs', input, '--preview-local-assets'], { cwd: root, encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr || result.stdout);
  const html = readFileSync(previewOutput, 'utf8');
  const navigation = html.match(/<tr class="freshine-roman-shade-navigation">[\s\S]*?(?=<tr>\s*<td class="freshine-roman-shade-background")/)?.[0];
  assert.ok(navigation, 'navigation must precede the unchanged hero background');
  assert.match(navigation, /width="75\.5%"[\s\S]*?bgcolor="#604211"/);
  assert.match(navigation, /width="24\.5%"[\s\S]*?bgcolor="#6B492C"/);
  assert.equal([...navigation.matchAll(/height="56"/g)].length, 2, 'both navigation cells must use the approved 56px height');
  assert.match(navigation, /height:min\(56px,9\.333334vw\)/);
  assert.match(navigation, /color:#FFFFFF/);
  assert.match(navigation, /Unlock An Extra 15% Off Your First Order At Freshine/);
  assert.match(navigation, /href="https:\/\/freshinelife.com\/"[\s\S]*?>SIGN UP<\/a>/);
  const navigationTextStyles = [...navigation.matchAll(/<(?:span|a)\b[^>]*\bstyle="([^"]*)"/g)].map(match => match[1]);
  assert.equal(navigationTextStyles.length, 2);
  for (const style of navigationTextStyles) {
    assert.match(style, /^display:block;/, 'both navigation labels must share the same centered line box');
    assert.match(style, /font-family:Montserrat,Arial,Helvetica,sans-serif/);
    assert.match(style, /font-size:16px;font-size:min\(16px,3vw\);font-weight:500/);
    assert.match(style, /line-height:20px;line-height:min\(20px,4vw\)/);
    assert.match(style, /letter-spacing:0px;text-align:center/);
  }
  assert.ok(html.includes(cta.replaceAll('&', '&amp;')));
  for (const text of ['Your Exclusive Discount', 'UP   TO', '70% Off', 'Bring Home The Look You Love', 'Decorate your home now']) assert.ok(html.includes(text), text);
  const eyebrowStyle = html.match(/<table class="freshine-roman-shade-eyebrow"[^>]*>\s*<tr><td[^>]*style="([^"]*)"/)?.[1];
  assert.ok(eyebrowStyle, 'eyebrow must retain its centered table cell');
  assert.match(eyebrowStyle, /font-size:21px;font-size:min\(21px,3\.5vw\);font-weight:500;line-height:26px;line-height:min\(26px,4\.333333vw\);letter-spacing:0px/);
  const ctaStyle = html.match(/<a[^>]*data-freshine-href-slot="hero\.cta\.url"[^>]*style="([^"]*)"/)?.[1];
  assert.ok(ctaStyle, 'tracked CTA must retain its editable anchor');
  assert.match(ctaStyle, /font-size:16px;font-size:max\(12px,min\(16px,2\.666667vw\)\);font-weight:600;line-height:20px;line-height:min\(20px,3\.333333vw\);letter-spacing:0px;text-align:center/);
  assert.match(ctaStyle, /padding:17\.5px 4px;padding:max\(12px,min\(17\.5px,2\.916667vw\)\)/, 'CTA must preserve its desktop 55px and mobile 44px outer height');
  const tagStyle = html.match(/<img[^>]*role="presentation"[^>]*style="([^"]*)"/)?.[1];
  assert.ok(tagStyle);
  assert.match(tagStyle, /margin:-2px 0 2px auto;margin:max\(-2px,-0\.333333vw\) 0 min\(2px,0\.333333vw\) auto/, 'the tag must offset its 4px transparent source edge so the visible top line meets the eyebrow bottom border without shifting following content');
  assert.match(html, /href="https:\/\/freshinelife.com\/"/);
  assert.doesNotMatch(html, /asset:\/\/|\{\{|FRESHINE_IF_SETTING|navigation\.visible/);
  const template = readFileSync(resolve(directory, 'component.template.v1.html'), 'utf8');
  assert.doesNotMatch(template, /<style\b|@media|display:\s*(?:flex|grid)|position:\s*(?:absolute|fixed)|<div\b/i);
  assert.match(template, /max-width:600px/);
  assert.match(template, /height:min\(761px,126\.833333vw\)/);
  assert.match(template, /min\(80px,13\.333333vw\)/);
  assert.match(template, /rgba\(255,255,255,0\.7\)/);
  const hiddenInput = resolve(temporary, 'without-navigation.json');
  composition.components[0].settings['navigation.visible'] = false;
  writeFileSync(hiddenInput, JSON.stringify(composition));
  const hiddenResult = spawnSync(process.execPath, ['build-email-template.v1.mjs', hiddenInput, '--preview-local-assets'], { cwd: root, encoding: 'utf8' });
  assert.equal(hiddenResult.status, 0, hiddenResult.stderr || hiddenResult.stdout);
  const hiddenHtml = readFileSync(previewOutput, 'utf8');
  assert.doesNotMatch(hiddenHtml, /freshine-roman-shade-navigation|SIGN UP|FRESHINE_IF_SETTING/);
  const bodyFrom = output => output.slice(output.indexOf('<td class="freshine-roman-shade-background"'));
  assert.equal(bodyFrom(hiddenHtml), bodyFrom(html), 'turning off navigation must not change the hero body');
});
